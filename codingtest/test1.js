/*
고객 상담 센터를 방문한 고객들의 상담 시작 시각과 종료 시각을 기록한 후,
적어도 한 명 이상의 고객이 상담을 진행하고있던 시간은 얼마나 되는지 알아보려 합니다.
단, 시각은 0분부터 시작하며, 모든 상담은 정확히 분 단위로 진행됩니다.
예를 들어 상담 시작 시각이 1분, 상담 종료 시각이 4분인 경우 정확히 1분 0초인 순간에 상담을 시작해서 정확히 4분 0초가 되는순간에 상담을 종료했음을 의미합니다.
따라서 이 경우, 상담을 진행한 시간은 3분입니다.
다음은 고객 3명의 상담 시각을 나타낸 예시입니다.
상담 시작 시각 상담 종료 시각1 43 58 101분 ~ 4분 사이에 고객 한명이 상담을 했으며, 3분 ~ 5분 사이에 다른 고객 한 명이 상담을 진행했습니다.
따라서 1분 ~ 5분 사이에는 적어도 한명 이상의 고객이 상담을 진행했습니다.
이후 8분 ~ 10분에도 고객 한 명이 상담을진행했으므로, 적어도 한 명 이상의 고객이 상담을 진행한 시간은 총 4분 + 2분 = 6분이 됩니다.
각 고객별 상담 시작 시각과 종료 시각이 담긴 2차원 배열 customer가 매개변수로 주어질 때,
적어도 한 명 이상의 고객이상담을 진행하고 있던 시간은 총 몇 분인지 return 하도록 solution 함수를 완성해주세요.
제한 사항- customer는 가로(열_ 길이가 2, 세로(행) 길이가 1이상 100,000이하인 2차원 배열입니다.
- customer의 각 행은 [상담 시작 시각, 상담 종료시각]과 같은 형식으로 들어있습니다.
- 항상 (상담 시작 시각 < 상담 종료 시각)으로 주어집니다.
- 상담 종료 시각은 0분이상 10,000,000분 이하인 정수입니다.
- 데이터가 상담을 시작한 시각 순서로 정렬되어 있지 않음에 주의하세요.
입출력 예시
customer result
[[1,4], [3,5], [8,10]] 6[[1,2], [3,4]] 2[[1,10], [2,8], [3,5]] 9
[[200,300],[100,200]] 200
입출력 예 #2
1분 ~ 2분, 3분 ~ 4분에 상담을 진행했으며, 적어도 한 명 이상의 고객이 상담을 진행한 시간은 1분 + 1분 = 2분입니다.
입출력 예 #3
1분 ~ 10분에 적어도 한명 이상의 고객이 상담을 진행했으며, 적어도 한명 이상의 고객이 상담을 진행한 시간은 9분입니다.
입출력 예 #4
100분 ~ 200분과 200 ~ 300분 사이에 상담을 진행했으며, 적어도 한명 이상의 고객이 상담을 진행한 시간은 100분 + 100분 = 200분입니다.
 */
function solution(customer) {
  customer.sort((a, b) => a[0] - b[0]);

  let total_time = 0;
  let current_start = customer[0][0];
  let current_end = customer[0][1];

  for (let i = 1; i < customer.length; i++) {
    let [start, end] = customer[i];

    if (start <= current_end) {
      current_end = Math.max(current_end, end);
    } else {
      total_time += current_end - current_start;
      current_start = start;
      current_end = end;
    }
  }

  total_time += current_end - current_start;

  return total_time;
}

